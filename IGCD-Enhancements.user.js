            const link = document.createElement('a');
            link.href = searchUrl;
            link.textContent = name;
            Object.assign(link.style, {
                color: 'inherit',
                fontFamily: 'inherit',
                fontSize: 'inherit',
                textDecoration: 'none',
                cursor: 'pointer'
            });

